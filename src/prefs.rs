//! Settings that belong to this computer, not to a show: kept as `prefs.json`
//! in the log folder beside the window layout.

use serde::{Deserialize, Serialize};
use std::path::Path;

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Prefs {
    /// Let the graphics hardware decode video where it can (FFmpeg's
    /// `-hwaccel auto`, which falls back to the processor for what it can't).
    #[serde(default)]
    pub hw_decode: bool,
    /// Started in show mode (the show can't be edited), as it was left.
    #[serde(default)]
    pub show_mode: bool,
    /// Let send cues run programs on this computer. Off unless turned on here,
    /// since a show can come from anywhere.
    #[serde(default)]
    pub allow_scripts: bool,
    /// Let a show start a streaming server on this computer (a display's Send
    /// out set to run the server in NewQ). Turned on by ticking that box here;
    /// a show opened from somewhere else can't start one before that.
    #[serde(default, skip_serializing_if = "is_false")]
    pub allow_hosting: bool,
    /// The monitors Test Mode shows its tests on (each by its make and model, or
    /// the name the system gives it); none = the displays of the show.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub test_displays: Vec<String>,
    /// Let the computer sleep and the display switch off while outputs are
    /// open (NewQ holds it awake by default; see `awake.rs`).
    #[serde(default, skip_serializing_if = "is_false")]
    pub let_computer_sleep: bool,
    /// Draw the output's frame rate on its picture (the Preview pane's checkbox).
    #[serde(default, skip_serializing_if = "is_false")]
    pub fps_on_output: bool,
    /// A presenter-style remote's buttons are acted on (see `clicker`), and the
    /// keys learned for its GO and Back buttons.
    #[serde(default, skip_serializing_if = "is_false")]
    pub clicker_on: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub clicker_go: Option<u32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub clicker_back: Option<u32>,
    /// Test Mode plays a heavier lap.
    #[serde(default, skip_serializing_if = "is_false")]
    pub test_heavy: bool,
    /// The audio device Test Mode plays on; none = the show's own outputs.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub test_sound: Option<String>,
    /// Test Mode runs with the sound off (everything still mixed).
    #[serde(default, skip_serializing_if = "is_false")]
    pub test_muted: bool,
    /// The test last chosen in Test Mode's window, chosen again when it opens.
    #[serde(default, skip_serializing_if = "TestPick::is_default")]
    pub test_pick: TestPick,
    /// Test Mode loads the show network with generated bytes while a test
    /// runs across it (`net::load`); Off by default.
    #[serde(default, skip_serializing_if = "crate::net::load::LoadLevel::is_off")]
    pub test_load: crate::net::load::LoadLevel,
    /// The new interface (editor, operator and patch views) in place of the panes.
    #[serde(default, skip_serializing_if = "is_false")]
    pub new_layout: bool,
    /// How much the log says (see `logging`).
    #[serde(default, skip_serializing_if = "is_default_level")]
    pub log_level: crate::logging::LogLevel,
    /// Where the timeline editor goes: a pane, or a workspace of its own.
    #[serde(default, skip_serializing_if = "TimelineLayout::is_pane")]
    pub timeline_layout: TimelineLayout,
    /// How the timeline editor's view keeps a running playhead in sight.
    #[serde(default, skip_serializing_if = "TimelineFollow::is_page")]
    pub timeline_follow: TimelineFollow,
    /// The start-at-login entries older NewQs made by themselves were removed
    /// on this computer, once (`autostart::at_start`): every entry since was
    /// ticked by someone and is kept.
    #[serde(default, skip_serializing_if = "is_false")]
    pub start_at_login_cleaned: bool,
}

/// What Test Mode's window has chosen: a length and what to test.
///
/// In the file as `{"level": .., "parts": {..}}`. A file from before the
/// ticks (0.24 and earlier) has a `flavour` and maybe `debug`: a cue test is
/// the cue list ticked, a timeline test the timeline (the debug test is now
/// under More and isn't remembered). For those versions the file also says
/// `flavour` Timeline when only the timeline is ticked.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
#[serde(from = "PickFile", into = "PickFile")]
pub struct TestPick {
    pub level: crate::testmode::Level,
    pub parts: crate::testmode::choice::Parts,
}

/// `TestPick` as the file has it, old and new.
#[derive(Clone, Copy, Serialize, Deserialize)]
struct PickFile {
    level: crate::testmode::Level,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    flavour: Option<crate::testmode::Flavour>,
    #[serde(default, skip_serializing_if = "is_false")]
    debug: bool,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    parts: Option<crate::testmode::choice::Parts>,
}

impl From<PickFile> for TestPick {
    fn from(f: PickFile) -> TestPick {
        use crate::testmode::Flavour;
        let parts = f.parts.unwrap_or(crate::testmode::choice::Parts {
            cue_list: f.flavour != Some(Flavour::Timeline),
            timeline: f.flavour == Some(Flavour::Timeline),
            network: false,
        });
        TestPick {
            level: f.level,
            parts,
        }
    }
}

impl From<TestPick> for PickFile {
    fn from(p: TestPick) -> PickFile {
        let only_timeline = p.parts.timeline && !p.parts.cue_list;
        PickFile {
            level: p.level,
            flavour: only_timeline.then_some(crate::testmode::Flavour::Timeline),
            debug: false,
            parts: Some(p.parts),
        }
    }
}

impl Default for TestPick {
    /// What the window starts with: the short cue list test.
    fn default() -> TestPick {
        TestPick {
            level: crate::testmode::Level::Short,
            parts: crate::testmode::choice::Parts::default(),
        }
    }
}

impl TestPick {
    fn is_default(&self) -> bool {
        *self == TestPick::default()
    }
}

/// Where the timeline editor is shown.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum TimelineLayout {
    /// A pane of the dock (the new interface: a panel under the cue list).
    #[default]
    Pane,
    /// A workspace that takes the place of the panes while it is open.
    Workspace,
}

impl TimelineLayout {
    fn is_pane(&self) -> bool {
        *self == TimelineLayout::Pane
    }
}

/// How the timeline editor's view follows the playhead while the run moves.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum TimelineFollow {
    /// Turn the page as it nears the right-hand edge.
    #[default]
    Page,
    /// Keep it in the middle, the tracks creeping under it.
    Centre,
}

impl TimelineFollow {
    fn is_page(&self) -> bool {
        *self == TimelineFollow::Page
    }
}

fn is_default_level(l: &crate::logging::LogLevel) -> bool {
    *l == crate::logging::LogLevel::default()
}

fn is_false(b: &bool) -> bool {
    !*b
}

const FILE: &str = "prefs.json";

impl Prefs {
    /// The saved settings; the defaults if there are none or they can't be read.
    pub fn load(dir: &Path) -> Prefs {
        std::fs::read_to_string(dir.join(FILE))
            .ok()
            .and_then(|t| serde_json::from_str(&t).ok())
            .unwrap_or_default()
    }

    pub fn save(&self, dir: &Path) -> std::io::Result<()> {
        std::fs::create_dir_all(dir)?;
        let tmp = dir.join(format!("{FILE}.tmp"));
        std::fs::write(
            &tmp,
            serde_json::to_string(self).map_err(std::io::Error::other)?,
        )?;
        std::fs::rename(&tmp, dir.join(FILE))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn settings_are_saved_and_a_missing_or_damaged_file_gives_the_defaults() {
        let dir = std::env::temp_dir().join("newq_test_prefs");
        let _ = std::fs::remove_dir_all(&dir);
        assert_eq!(Prefs::load(&dir), Prefs::default());
        let p = Prefs {
            hw_decode: true,
            show_mode: true,
            allow_scripts: true,
            allow_hosting: true,
            test_displays: vec!["Dell U2720Q".into()],
            test_sound: Some("USB Interface".into()),
            test_muted: true,
            fps_on_output: true,
            let_computer_sleep: true,
            test_heavy: true,
            test_load: crate::net::load::LoadLevel::Heavy,
            clicker_on: true,
            clicker_go: Some(0x51),
            clicker_back: Some(0x49),
            new_layout: true,
            log_level: crate::logging::LogLevel::Debug,
            timeline_layout: TimelineLayout::Workspace,
            timeline_follow: TimelineFollow::Centre,
            start_at_login_cleaned: true,
            test_pick: TestPick {
                level: crate::testmode::Level::Medium,
                parts: crate::testmode::choice::Parts {
                    cue_list: false,
                    timeline: true,
                    network: false,
                },
            },
        };
        p.save(&dir).unwrap();
        assert_eq!(Prefs::load(&dir), p);
        assert!(
            serde_json::to_string(&p)
                .unwrap()
                .contains("\"test_load\":\"heavy\"")
        );
        // A load from a later NewQ that this one doesn't know is Off, the
        // rest of the file kept.
        std::fs::write(
            dir.join(FILE),
            "{\"test_load\":\"stormy\",\"hw_decode\":true}",
        )
        .unwrap();
        let later = Prefs::load(&dir);
        assert!(later.hw_decode && later.test_load.is_off());
        std::fs::write(dir.join(FILE), "not json").unwrap();
        assert_eq!(Prefs::load(&dir), Prefs::default());
        // A file from before a setting existed.
        std::fs::write(dir.join(FILE), "{}").unwrap();
        assert!(!Prefs::load(&dir).hw_decode);
        // Defaults are not written, so older versions read the file as before.
        let json = serde_json::to_string(&Prefs::default()).unwrap();
        assert!(!json.contains("test_"), "{json}");
        assert!(!json.contains("new_layout"), "{json}");
        assert!(
            !json.contains("let_computer_sleep") && !json.contains("fps_on_output"),
            "{json}"
        );
        assert!(!json.contains("clicker"), "{json}");
        assert!(!json.contains("log_level"), "{json}");
        assert!(!json.contains("timeline"), "{json}");
        assert!(!json.contains("start_at_login"), "{json}");
        assert!(
            serde_json::to_string(&p)
                .unwrap()
                .contains("\"start_at_login_cleaned\":true")
        );
        assert!(
            serde_json::to_string(&p)
                .unwrap()
                .contains("\"timeline_layout\":\"Workspace\"")
        );
        assert!(
            serde_json::to_string(&p)
                .unwrap()
                .contains("\"timeline_follow\":\"Centre\"")
        );
        // The level is a word in the file, and one this version doesn't know
        // (from a newer one) gives the defaults, not a failure to start.
        assert!(
            serde_json::to_string(&p)
                .unwrap()
                .contains("\"log_level\":\"debug\"")
        );
        std::fs::write(
            dir.join(FILE),
            "{\"log_level\":\"trace\",\"hw_decode\":true}",
        )
        .unwrap();
        assert_eq!(Prefs::load(&dir).log_level, crate::logging::LogLevel::Trace);
        std::fs::write(dir.join(FILE), "{\"log_level\":\"chatty\"}").unwrap();
        assert_eq!(Prefs::load(&dir), Prefs::default());
        // The test chosen in Test Mode: its words in the file, read back, and
        // what an older NewQ reads of them (only the timeline: its flavour).
        let text = serde_json::to_string(&p).unwrap();
        assert!(
            text.contains("\"test_pick\":{\"level\":\"Medium\",\"flavour\":\"Timeline\",\"parts\":{\"cue_list\":false,\"timeline\":true,\"network\":false}}"),
            "{text}"
        );
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn a_test_chosen_before_the_ticks_is_chosen_again_as_ticks() {
        use crate::testmode::Level;
        use crate::testmode::choice::Parts;
        let dir = std::env::temp_dir().join(format!("newq_prefs_pick_{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let read = |json: &str| {
            std::fs::write(dir.join(FILE), json).unwrap();
            Prefs::load(&dir).test_pick
        };
        let ticks = |cue_list, timeline, network| Parts {
            cue_list,
            timeline,
            network,
        };
        // 0.24's words: a level of a flavour, or the debug test.
        let p = read("{\"test_pick\":{\"level\":\"Long\",\"debug\":true}}");
        assert_eq!((p.level, p.parts), (Level::Long, ticks(true, false, false)));
        let p = read("{\"test_pick\":{\"level\":\"Medium\",\"flavour\":\"Timeline\"}}");
        assert_eq!(
            (p.level, p.parts),
            (Level::Medium, ticks(false, true, false))
        );
        let p = read("{\"test_pick\":{\"level\":\"Short\",\"flavour\":\"Cues\"}}");
        assert_eq!(p, TestPick::default());
        // Today's: the ticks win over a flavour written for older versions.
        let p = read(
            "{\"test_pick\":{\"level\":\"Short\",\"flavour\":\"Timeline\",\"parts\":{\"cue_list\":true,\"timeline\":true,\"network\":true}}}",
        );
        assert_eq!(p.parts, ticks(true, true, true));
        // Round trip, and the default isn't written.
        let mut prefs = Prefs::default();
        prefs.test_pick.parts = ticks(true, false, true);
        prefs.save(&dir).unwrap();
        assert_eq!(Prefs::load(&dir).test_pick, prefs.test_pick);
        let text = std::fs::read_to_string(dir.join(FILE)).unwrap();
        assert!(!text.contains("flavour"), "{text}");
        assert!(
            !serde_json::to_string(&Prefs::default())
                .unwrap()
                .contains("test_pick")
        );
        let _ = std::fs::remove_dir_all(dir);
    }
}
